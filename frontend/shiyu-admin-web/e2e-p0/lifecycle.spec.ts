import { verifyMaintenanceFlow } from './maintenance-flow';
import { verifyTeamFlow } from './team-flow';
import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

test('首次安装、登录、版本信息、上传与会话退出', async ({ page }, testInfo) => {
  const failures: string[] = [];
  page.on('response', (response) => {
    if (response.url().includes('/api/') && response.status() >= 400) failures.push(`${response.status()} ${new URL(response.url()).pathname}`);
  });
  await page.goto('/');
  await expect(page).toHaveURL(/\/setup$/);
  await expect(page.getByText('数据库：已连接')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('setup.png'), fullPage: true });
  const { root } = JSON.parse(readFileSync('.p0-e2e.json', 'utf8'));
  await page.getByLabel('安装授权码').fill(readFileSync(join(root, 'setup-token'), 'utf8').trim());
  await page.getByLabel('系统名称').fill('P0 验证管理系统');
  await page.getByLabel('管理员账号').fill('owner');
  await page.getByLabel('管理员密码', { exact: true }).fill('Shiyu!Browser2026');
  await page.getByLabel('确认密码').fill('Shiyu!Browser2026');
  await page.getByRole('button', { name: '完成安装' }).click();
  await expect(page).toHaveURL(/\/user\/login$/);
  await expect(page.getByRole('heading', { name: 'P0 验证管理系统' })).toBeVisible();
  await expect(page.getByPlaceholder('密码', { exact: true })).toBeEmpty();
  await page.getByPlaceholder('用户名', { exact: true }).fill('owner');
  await page.getByPlaceholder('密码', { exact: true }).fill('Shiyu!Browser2026');
  await page.getByRole('button', { name: '进入控制台' }).click();
  await expect(page).toHaveURL(/\/welcome$/);
  await page.getByRole('link', { name: '版本与升级' }).click();
  await expect(page.getByText('0.3.0-dev', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('version.png'), fullPage: true });
  await page.getByRole('tab', { name: '升级与回退' }).click();
  await expect(page.getByText('旧版默认上传目录', { exact: false })).toBeVisible();
  await page.goto('/system/files');
  await page.locator('input[type=file]').setInputFiles({ name: 'browser-proof.txt', mimeType: 'text/plain', buffer: Buffer.from('P0 browser upload') });
  await expect(page.getByText('browser-proof.txt', { exact: true })).toBeVisible();
  await verifyTeamFlow(page, testInfo);
  await verifyMaintenanceFlow(page, testInfo);
  expect(failures, '安装、设置、申请与审批不应出现接口错误').toEqual([]);
  const token = await page.evaluate(() => localStorage.getItem('shiyu_token'));
  const result = await page.request.post('/api/v1/system/auth/logout', { headers: { Authorization: `Bearer ${token}` } });
  expect(result.status()).toBe(200);
  const profile = await page.request.get('/api/v1/system/profile', { headers: { Authorization: `Bearer ${token}` } });
  expect(profile.status()).toBe(401);
  await page.reload();
  await expect(page).toHaveURL(/\/user\/login$/);
  await page.getByPlaceholder('用户名', { exact: true }).fill('owner');
  await page.getByPlaceholder('密码', { exact: true }).fill('Shiyu!Browser2026');
  await page.getByRole('button', { name: '进入控制台' }).click();
  await expect(page).toHaveURL(/\/welcome$/);
  await page.goto('/account/password');
  await page.getByLabel('原密码', { exact: true }).fill('Shiyu!Browser2026');
  await page.getByLabel('新密码', { exact: true }).fill('Shiyu!BrowserChanged2026');
  await page.getByLabel('确认新密码', { exact: true }).fill('Shiyu!BrowserChanged2026');
  await page.getByRole('button', { name: '提 交' }).click();
  await expect(page).toHaveURL(/\/user\/login$/);
  await expect(page.getByPlaceholder('密码', { exact: true })).toBeEmpty();
});
